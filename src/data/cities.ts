export interface GeoCity {
  id: string
  name: string
  country: string
  admin1?: string
  lat: number
  lon: number
  elev: number
}

export interface City extends GeoCity {
  high: number[]
  low: number[]
  precip: number[]
  sun: number[]
  sunrise: string[]
  sunset: string[]
  source?: string  // X-Climato-Source slug: 'open-meteo' | 'nasa-power' | undefined for static-served entries
}

